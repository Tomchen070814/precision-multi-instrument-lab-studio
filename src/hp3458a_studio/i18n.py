def tr(language: str, text: str, **values) -> str:
    translated = EN.get(text, text) if language == "en" else text
    if values:
        return translated.format(**values)
    return translated


def function_name(language: str, function: MeasurementFunction) -> str:
    return FUNCTION_EN[function] if language == "en" else function.value
